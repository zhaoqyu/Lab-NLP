#!/usr/bin/env python3
"""
Module for comparing Key-Value Store (KVS) intrinsic value scores.

This script acts as the primary evaluation consumer for the results
generated by the training pipeline. It rigorously compares the JSON 
outputs of a base model against a trained model, calculating the 
Target Value Rating Drop and Other Values' Variance.

Author: Ali (Evaluation Module)
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

# Configure strict academic logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s"
)
logger = logging.getLogger(__name__)


def parse_args() -> argparse.Namespace:
    """Parse robust command-line arguments for cluster integration."""
    parser = argparse.ArgumentParser(description="Strict comparison of KVS evaluation results.")
    parser.add_argument(
        "--trained", 
        type=Path, 
        required=True, 
        help="Path to the trained-model KVS score JSON generated by the training pipeline."
    )
    parser.add_argument(
        "--base", 
        type=Path, 
        default=None, 
        help="Optional path to the base-model KVS score JSON. If omitted, only trained stats are reported."
    )
    parser.add_argument(
        "--target-values", 
        nargs="+", 
        default=[],
        help="List of target values deliberately manipulated during training."
    )
    parser.add_argument(
        "--output-json", 
        type=Path, 
        default=Path("value_alignment_eval/simulate_result/kvs_comparison_rigorous.json")
    )
    parser.add_argument(
        "--output-csv", 
        type=Path, 
        default=Path("value_alignment_eval/simulate_result/kvs_comparison_rigorous.csv")
    )
    return parser.parse_args()


def load_summary(path: Optional[Path]) -> Dict[str, Any]:
    """Safely load and validate the JSON summary data."""
    if path is None or not path.exists():
        if path is not None:
            logger.warning(f"File not found: {path}. Proceeding with empty summary.")
        return {}
        
    try:
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f)
            # Ensure we are extracting the summary dictionary
            if "summary" in data:
                logger.info(f"Successfully loaded nested summary from {path}.")
                return data["summary"]
            logger.info(f"Successfully loaded flat summary from {path}.")
            return data
    except json.JSONDecodeError as e:
        logger.error(f"Malformed JSON in file {path}: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error loading {path}: {e}")
        raise


def extract_metric(summary: Dict[str, Any], value: str, field: str) -> Optional[float]:
    """Extract a specific metric with strict type checking."""
    value_summary = summary.get(value, {})
    result = value_summary.get(field)
    try:
        return float(result) if result is not None else None
    except ValueError:
        logger.warning(f"Invalid numeric value for {field} in {value}: {result}")
        return None


def main() -> None:
    args = parse_args()
    logger.info("Initializing rigorous evaluation comparison...")

    # Pass 1: Load results generated by teammates
    base_data = load_summary(args.base)
    trained_data = load_summary(args.trained)
    
    if not trained_data:
        logger.error("Trained data is completely empty or missing. Evaluation cannot proceed.")
        return

    # Pass 2: Aggregate values ensuring no duplicates
    all_values = sorted(set(base_data.keys()) | set(trained_data.keys()))
    rows: List[Dict[str, Any]] = []

    logger.info(f"Evaluating {len(all_values)} unique value axes.")

    for value in all_values:
        base_mean = extract_metric(base_data, value, "mean_rating")
        trained_mean = extract_metric(trained_data, value, "mean_rating")
        
        delta = None
        if base_mean is not None and trained_mean is not None:
            delta = trained_mean - base_mean
            
        rows.append({
            "value": value,
            "base_mean": base_mean,
            "trained_mean": trained_mean,
            "delta": delta,
            "base_std": extract_metric(base_data, value, "std_rating"),
            "trained_std": extract_metric(trained_data, value, "std_rating"),
            "base_count": base_data.get(value, {}).get("count", 0),
            "trained_count": trained_data.get(value, {}).get("count", 0),
            "is_target": value in args.target_values,
        })

    # Pass 3: Compute robust comparative metrics
    other_deltas = [r["delta"] for r in rows if r["delta"] is not None and not r["is_target"]]
    target_deltas = [r["delta"] for r in rows if r["delta"] is not None and r["is_target"]]
    
    target_mean_delta = sum(target_deltas) / len(target_deltas) if target_deltas else None
    other_mean_delta = sum(other_deltas) / len(other_deltas) if other_deltas else None
    
    other_variance = None
    if other_deltas:
        mean_o = sum(other_deltas) / len(other_deltas)
        other_variance = sum((d - mean_o) ** 2 for d in other_deltas) / len(other_deltas)

    comparison_results = {
        "target_values_tracked": args.target_values,
        "target_mean_delta": target_mean_delta,
        "other_values_mean_delta": other_mean_delta,
        "other_values_variance": other_variance,
        "per_value_analysis": rows,
    }

    # Ensure output directories exist securely
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    
    with args.output_json.open("w", encoding="utf-8") as f:
        json.dump(comparison_results, f, indent=2, ensure_ascii=False)
    logger.info(f"Strict JSON results saved to {args.output_json}")

    if args.output_csv and rows:
        args.output_csv.parent.mkdir(parents=True, exist_ok=True)
        with args.output_csv.open("w", newline="", encoding="utf-8") as handle:
            fieldnames = list(rows[0].keys())
            writer = csv.DictWriter(handle, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(rows)
        logger.info(f"Strict CSV results saved to {args.output_csv}")

    logger.info("Evaluation Complete. High-level summary:")
    logger.info(json.dumps({k: v for k, v in comparison_results.items() if k != "per_value_analysis"}, indent=2))


if __name__ == "__main__":
    main()
